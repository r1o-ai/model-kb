#!/usr/bin/env python3
"""recipe_store.py — the one writer of hand-made recipe data (contract E-Q2/E-Q4).

Store:     <root>/recipes.jsonl — one record per (model, engine, source),
           source ∈ research | benchmark | user, each with a history[] of patches.
           The only hand-made data in model-kb; records.jsonl is regenerated.
Snapshot:  <root>/recipes.snapshot.json — GENERATED, 0444, a pure function of the
           store. The chat path reads only this file, so a model-kb outage cannot
           stop chat. Never edit it; the guard rejects writes to it.
Fold:      pipeline.py calls fold_into_records() under its lock on every
           generation. It re-adds the store as kind=authored_recipe rows (so they
           survive the recipes clobber) and computes servable / servable_on /
           servable_reason for every recipe row from the live engine union.

Writes happen only on the writer node: the node whose crontab runs this
install's pipeline.py. They take the same .ingest.lock as the pipeline; when it
is held, put() raises LockHeld and the CLI exits 75 ("ingest running, retry").

Usage:
  python3 recipe_store.py put --model M --engine E --source user --patch '{"sampling": {"temperature": 0.2}}'
  python3 recipe_store.py get --model M --engine E --source user
  python3 recipe_store.py export
  python3 recipe_store.py writer        # is this node the writer? (exit 0 yes / 77 no)
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from lib.engines import EngineCatalogUnavailable, live_engine_ids  # noqa: E402
from lib.ingest_lock import EXIT_LOCKED, acquire_lock  # noqa: E402

STORE = "recipes.jsonl"
SNAPSHOT = "recipes.snapshot.json"
GENERATED = "GENERATED by model-kb export_recipe_snapshot — do not edit"
SOURCES = ("research", "benchmark", "user")  # schema enum; later entries override earlier ones
AUTHORED_KIND = "authored_recipe"
RECIPE_KINDS = ("serve_recipe", AUTHORED_KIND)

EXIT_BAD_INPUT = 2
EXIT_NO_ENGINES = 4
EXIT_NOT_WRITER = 77  # EX_NOPERM
PUT_LOCK_TIMEOUT_S = float(os.getenv("MODEL_KB_PUT_LOCK_TIMEOUT_S", "10"))

_ENGINE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.\-]*$")
_PATH_TOKEN = re.compile(r"[^\s'\"]+")
__all__ = [
    "EXIT_LOCKED", "EXIT_NOT_WRITER", "EXIT_NO_ENGINES", "EngineCatalogUnavailable",
    "LockHeld", "NotWriterNode", "RecipeError", "export_recipe_snapshot", "fold_into_records",
    "get", "is_writer_node", "put",
]


class RecipeError(ValueError):
    """Bad input; nothing was written."""


class LockHeld(RuntimeError):
    """An ingest holds .ingest.lock; nothing was written — retry after it finishes."""


class NotWriterNode(RuntimeError):
    """This node does not run the pipeline, so it may not write the store."""


# -- writer node ---------------------------------------------------------------

def _root_spellings(root: Path) -> set[str]:
    """How a cron line or script can name this install: absolute or $HOME-relative."""
    out: set[str] = set()
    home = Path.home()
    for p in {Path(root).absolute(), Path(root).resolve()}:
        out.add(str(p))
        for h in {home, home.resolve()}:
            try:
                rel = p.relative_to(h)
            except ValueError:
                continue
            out |= {f"$HOME/{rel}", f"${{HOME}}/{rel}", f"~/{rel}"}
    return out


def _names_pipeline(text: str, spellings: set[str]) -> bool:
    return "pipeline.py" in text and any(s in text for s in spellings)


def is_writer_node(root: Path = ROOT) -> tuple[bool, str]:
    """(writer?, why). Writer = a crontab entry here runs this install's pipeline.py,
    directly or through a script it calls."""
    try:
        r = subprocess.run(["crontab", "-l"], capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"cannot read crontab: {e}"
    if r.returncode != 0:
        return False, "no crontab on this node"
    spellings = _root_spellings(root)
    for line in r.stdout.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if _names_pipeline(line, spellings):
            return True, f"crontab runs pipeline.py: {line[:160]}"
        for tok in _PATH_TOKEN.findall(line):
            p = Path(os.path.expanduser(os.path.expandvars(tok)))
            try:
                if not p.is_file() or p.stat().st_size > 256 * 1024:
                    continue
                text = p.read_text(errors="ignore")
            except OSError:
                continue
            if _names_pipeline(text, spellings):
                return True, f"crontab runs {p}, which runs pipeline.py"
    return False, f"no crontab entry on this node runs pipeline.py for {root}"


# -- store ---------------------------------------------------------------------

def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _key(r: dict[str, Any]) -> tuple[str, str, str]:
    return (str(r["model"]), str(r["engine"]), str(r["source"]))


def _load_store(root: Path) -> list[dict[str, Any]]:
    path = Path(root) / STORE
    if not path.exists():
        return []
    rows = []
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip():
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError as e:
            # Hand-made data: never silently drop a row.
            raise RecipeError(f"{path}:{n} is not JSON ({e}); fix it before writing") from e
    return rows


def _atomic_write(path: Path, text: str, mode: int | None = None) -> None:
    tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        if mode is not None:
            os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            tmp.unlink()


def _write_store(root: Path, rows: list[dict[str, Any]]) -> None:
    rows = sorted(rows, key=_key)
    _atomic_write(Path(root) / STORE, "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))


def _merge(base: dict[str, Any], patch: dict[str, Any]) -> dict[str, Any]:
    """Deep merge; a None value deletes the key."""
    out = copy.deepcopy(base)
    for k, v in patch.items():
        if v is None:
            out.pop(k, None)
        elif isinstance(v, dict):
            out[k] = _merge(out[k] if isinstance(out.get(k), dict) else {}, v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def _validate(model: Any, engine: Any, source: Any, patch: Any) -> None:
    if source not in SOURCES:
        raise RecipeError(f"source must be one of {', '.join(SOURCES)} (got {source!r})")
    if not isinstance(model, str) or not model.strip() or "\n" in model:
        raise RecipeError(f"model must be a non-empty single-line string (got {model!r})")
    if not isinstance(engine, str) or not _ENGINE_RE.match(engine):
        raise RecipeError(f"engine must be an engine id as asmi /serve/engines reports it (got {engine!r})")
    if not isinstance(patch, dict):
        raise RecipeError(f"patch must be a JSON object (got {type(patch).__name__})")


def get(root: Path = ROOT, *, model: str, engine: str, source: str) -> dict[str, Any] | None:
    want = (model, engine, source)
    return next((r for r in _load_store(root) if _key(r) == want), None)


def put(
    root: Path = ROOT,
    *,
    model: str,
    engine: str,
    source: str,
    patch: dict[str, Any],
    lock_timeout_s: float | None = None,
) -> dict[str, Any]:
    """Merge `patch` into the (model, engine, source) record, append it to history,
    rewrite the store atomically and re-export the snapshot — all under .ingest.lock."""
    _validate(model, engine, source, patch)
    ok, why = is_writer_node(root)
    if not ok:
        raise NotWriterNode(f"{why}; write on the node that runs the model-kb pipeline")
    lock = acquire_lock(root, PUT_LOCK_TIMEOUT_S if lock_timeout_s is None else lock_timeout_s,
                        who="recipe_store put")
    if not hasattr(lock, "fileno"):
        raise LockHeld(f"model-kb ingest running (lock held by {lock}); nothing written — retry after it finishes")
    try:
        rows = _load_store(root)
        rec = next((r for r in rows if _key(r) == (model, engine, source)), None)
        now = _now()
        if rec is None:
            rec = {"model": model, "engine": engine, "source": source, "recipe": {},
                   "created": now, "updated": now, "history": []}
            rows.append(rec)
        rec["recipe"] = _merge(rec.get("recipe") or {}, patch)
        rec["updated"] = now
        rec.setdefault("history", []).append({"at": now, "patch": patch})
        _write_store(root, rows)
        export_recipe_snapshot(root, rows)
        return copy.deepcopy(rec)
    finally:
        lock.close()


# -- snapshot ------------------------------------------------------------------

def snapshot_doc(rows: list[dict[str, Any]], store_sha256: str) -> dict[str, Any]:
    grouped: dict[tuple[str, str], dict[str, dict[str, Any]]] = {}
    for r in rows:
        grouped.setdefault((str(r["model"]), str(r["engine"])), {})[str(r["source"])] = r.get("recipe") or {}
    recipes = []
    for (model, engine), by_source in sorted(grouped.items()):
        effective: dict[str, Any] = {}
        for src in SOURCES:
            if src in by_source:
                effective = _merge(effective, by_source[src])
        recipes.append({"model": model, "engine": engine, "sources": by_source, "effective": effective})
    return {
        "GENERATED": GENERATED,
        "precedence": list(SOURCES),
        "schema": 1,
        "store": STORE,
        "store_sha256": store_sha256,
        "recipes": recipes,
    }


def export_recipe_snapshot(root: Path = ROOT, rows: list[dict[str, Any]] | None = None) -> Path:
    """Write recipes.snapshot.json (0444) from the store. Same store → same bytes."""
    root = Path(root)
    store = root / STORE
    rows = _load_store(root) if rows is None else rows
    sha = hashlib.sha256(store.read_bytes()).hexdigest() if store.exists() else ""
    text = json.dumps(snapshot_doc(rows, sha), ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    path = root / SNAPSHOT
    if path.exists() and path.read_text(encoding="utf-8") == text and (path.stat().st_mode & 0o777) == 0o444:
        return path
    _atomic_write(path, text, mode=0o444)
    return path


# -- fold (called by pipeline.py while it holds the lock) ------------------------

def _servability(engine: Any, engines: dict[str, list[str]]) -> dict[str, Any]:
    if not engine:
        return {"servable": False, "servable_on": [], "servable_reason": "recipe names no engine"}
    nodes = list(engines.get(str(engine)) or [])
    if nodes:
        return {"servable": True, "servable_on": nodes,
                "servable_reason": f"engine {engine} is declared by {len(nodes)} online node(s)"}
    return {"servable": False, "servable_on": [],
            "servable_reason": f"no online node declares engine {engine} (asmi /serve/engines)"}


def _authored_row(r: dict[str, Any]) -> dict[str, Any]:
    recipe = r.get("recipe") or {}
    model, engine, source = _key(r)
    return {
        "id": f"authored:{source}:{model}@{engine}",
        "kind": AUTHORED_KIND,
        "model": model,
        "engine": engine,
        "source": source,
        "recipe": recipe,
        "updated": r.get("updated"),
        "search_text": f"{model} {engine} {source} recipe {json.dumps(recipe, sort_keys=True)}",
    }


def fold_into_records(
    root: Path, records: Path, engines: dict[str, list[str]] | None = None
) -> dict[str, int]:
    """Re-add the store to records.jsonl and compute servability. The caller holds the lock.
    Raises EngineCatalogUnavailable (nothing written) when no node reports engines."""
    engines = live_engine_ids() if engines is None else engines
    if not engines:
        raise EngineCatalogUnavailable("engine union is empty")
    rows = []
    if records.exists():
        rows = [json.loads(l) for l in records.read_text().splitlines() if l.strip()]
    rows = [r for r in rows if r.get("kind") != AUTHORED_KIND]
    store = _load_store(root)
    rows += [_authored_row(r) for r in sorted(store, key=_key)]
    stats = {"authored": len(store), "servable": 0, "not_servable": 0}
    for r in rows:
        if r.get("kind") not in RECIPE_KINDS:
            continue
        engine = (r.get("serve") or {}).get("engine") if r.get("kind") == "serve_recipe" else r.get("engine")
        r.update(_servability(engine, engines))
        stats["servable" if r["servable"] else "not_servable"] += 1
    _atomic_write(records, "".join(json.dumps(r, ensure_ascii=False, default=str) + "\n" for r in rows))
    export_recipe_snapshot(root, store)
    return stats


# -- CLI -----------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="recipe_store")
    ap.add_argument("--root", type=Path, default=ROOT)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_put = sub.add_parser("put")
    p_get = sub.add_parser("get")
    for p in (p_put, p_get):
        p.add_argument("--model", required=True)
        p.add_argument("--engine", required=True)
        p.add_argument("--source", required=True)
    p_put.add_argument("--patch", required=True, help="JSON object; null deletes a key")
    p_put.add_argument("--lock-timeout", type=float, default=None)
    sub.add_parser("export")
    sub.add_parser("writer")
    args = ap.parse_args(argv)

    if args.cmd == "writer":
        ok, why = is_writer_node(args.root)
        print(why)
        return 0 if ok else EXIT_NOT_WRITER
    if args.cmd == "export":
        print(export_recipe_snapshot(args.root))
        return 0
    if args.cmd == "get":
        rec = get(args.root, model=args.model, engine=args.engine, source=args.source)
        print(json.dumps(rec, indent=2, ensure_ascii=False))
        return 0 if rec else 1
    try:
        patch = json.loads(args.patch)
        rec = put(args.root, model=args.model, engine=args.engine, source=args.source,
                  patch=patch, lock_timeout_s=args.lock_timeout)
    except LockHeld as e:
        print(f"RETRY: {e}", file=sys.stderr)
        return EXIT_LOCKED
    except NotWriterNode as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return EXIT_NOT_WRITER
    except (RecipeError, json.JSONDecodeError) as e:
        print(f"FAIL: {e}", file=sys.stderr)
        return EXIT_BAD_INPUT
    print(json.dumps(rec, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
